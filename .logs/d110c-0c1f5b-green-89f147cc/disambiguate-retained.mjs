import fs from 'node:fs';
import path from 'node:path';
import {execFileSync,spawnSync} from 'node:child_process';
import {loadConfigFromFile} from '/Users/aristotle/Documents/Projects/ts-drp-1/node_modules/vite/dist/node/index.js';
const root='/Users/aristotle/Documents/Projects/ts-drp-1',out=path.dirname(new URL(import.meta.url).pathname);
const frozen=JSON.parse(fs.readFileSync(path.join(out,'retained-exact-roster.json')));
const discovered=execFileSync('rg',['--files','tests','packages','examples'],{cwd:root,encoding:'utf8'}).trim().split('\n');
const candidates=[...new Set([...discovered,...frozen.collection.map(row=>path.relative(root,row.file))])];
const loaded=await loadConfigFromFile({command:'serve',mode:'test'},path.join(root,'vite.config.mts'));
const originalExcludes=loaded.config.test.exclude;
const match=(file,argument)=>{
 const t=path.join(root,file),f=path.join(root,argument);
 return (path.isAbsolute(f)&&t.startsWith(f))||file.toLowerCase().includes(f.toLowerCase())||file.toLowerCase().includes(path.relative(root,f).toLowerCase());
};
const ambiguous=[];
const roster=frozen.roster.map(row=>{
 const matched=candidates.filter(file=>row.files.some(argument=>match(file,argument)));
 const excluded=matched.filter(file=>!row.files.includes(file));
 const surviving=matched.filter(file=>!excluded.includes(file));
 if(JSON.stringify([...surviving].sort())!==JSON.stringify([...row.files].sort()))throw Error('Filter simulation differs '+row.label);
 if(excluded.length)ambiguous.push({label:row.label,files:row.files,excluded});
 return {...row,excludedSameSuffix:excluded,command:[...row.command,...(excluded.length?[...originalExcludes,...excluded].map(file=>'--exclude='+file):[])],...(row.label==='retained-02'||row.label==='retained-26'?{coveredBy:'retained-02/result.json root-audited exact13+21allpass union; do not rerun'}:{})};
});
const write=(file,value)=>fs.writeFileSync(path.join(out,file),JSON.stringify(value,null,2)+'\n',{flag:'wx'});
const report=JSON.parse(fs.readFileSync(path.join(out,'retained-02/result.json')));
const coverage=report.testResults.map(file=>({file:path.relative(root,file.name),total:file.assertionResults.length,allPassed:file.assertionResults.every(row=>row.status==='passed'&&row.failureMessages.length===0),assertions:file.assertionResults}));
if(report.success!==true||coverage.length!==2||coverage.some(file=>!file.allPassed))throw Error('Combined coverage differs');
write('retained-02-root-disposition.json',{classification:'Launcher selection anomaly, not test failure; root independently accepts exact intended gate02+gate26 coverage without rerun',coverage,originalNameMismatchPreserved:true});
const selected=[...new Set(ambiguous.flatMap(row=>row.files))];
const excluded=[...new Set(ambiguous.flatMap(row=>row.excluded))];
if(selected.some(file=>excluded.includes(file)))throw Error('Ambiguous collection check overlap');
const args=['pnpm','exec','vitest','list',...selected.map(file=>path.join(root,file)),...[...originalExcludes,...excluded].map(file=>'--exclude='+file),'--json'];
write('retained-runtime-roster.json',{...frozen,supersedes:'retained-exact-roster.json adds exact same-suffix exclusions and root-audited prior coverage only',roster,filterSimulation:{installedSource:'vitest3.1.1 cli-api filterFiles10448-10464 + globAllTestFiles10342-10360',originalExcludes,discoveredFiles:candidates,ambiguous},collectionCheck:{command:args,selected,excluded}});
const result=spawnSync(process.execPath,[path.join(out,'run.mjs'),'retained-exclusion-collection',root,...args],{stdio:'inherit'});
if(result.status!==0)process.exit(result.status??1);
const listed=JSON.parse(fs.readFileSync(path.join(out,'retained-exclusion-collection/stdout')));
const expected=frozen.collection.filter(row=>selected.includes(path.relative(root,row.file)));
const normalize=rows=>rows.map(row=>row.file+'\0'+row.name).sort();
const pass=JSON.stringify(normalize(listed))===JSON.stringify(normalize(expected));
write('retained-exclusion-validation.json',{pass,actual:listed,expected,selected,excluded});
console.log(JSON.stringify({pass,ambiguousGates:ambiguous.length,listedAssertions:listed.length,selectedFiles:selected.length,exclusions:excluded}));
process.exitCode=pass?0:1;
