import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
const root = '/Users/aristotle/Documents/Projects/ts-drp-1';
const evidence = path.join(root, '.logs/d110c-w0-regression-readiness-7efe33dd');
const read = name => JSON.parse(fs.readFileSync(path.join(evidence, name)));
const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const label = process.argv[2];
const roster = read('runtime-roster.json');
const gate = roster.gates.find(entry => entry.label === label);
assert.ok(gate);
const result = read(label + '/result.json');
const status = read(label + '/status.json');
const actual = result.testResults.flatMap(file => file.assertionResults.map(test => {
  assert.equal(test.status, 'passed');
  assert.deepEqual(test.failureMessages, []);
  return JSON.stringify([path.relative(root, file.name), [...test.ancestorTitles, test.title].join(' > ')]);
}));
assert.deepEqual(actual.sort(), gate.entries.map(entry => JSON.stringify([entry.file, entry.name])).sort());
assert.equal(new Set(actual).size, actual.length);
assert.equal(result.testResults.length, gate.files.length);
assert.equal(result.numTotalTests, actual.length);
assert.equal(result.numPassedTests, actual.length);
assert.equal(result.numFailedTests + result.numPendingTests + result.numTodoTests, 0);
assert.equal(result.success, true);
assert.equal(status.code, 0);
assert.equal(status.timedOut, false);
assert.equal(status.quiescent, true);
assert.deepEqual(status.cleanup, []);
assert.deepEqual(status.remainingOwnedGroup, []);
assert.ok(status.elapsedMs < gate.budgetMs);
for (const [file, digest] of Object.entries(roster.inputHashes)) assert.equal(hash(fs.readFileSync(file)), digest, file);
for (const [file, digest] of Object.entries(roster.artifactHashes)) assert.equal(hash(fs.readFileSync(path.join(evidence, file))), digest, file);
const validation = read(label + '/validation.json');
assert.equal(validation.exactRoster, true);
assert.equal(validation.postCustodyExact, true);
assert.equal(validation.allInputsExact, true);
assert.equal(validation.green, true);
console.log(JSON.stringify({ gate: label, files: gate.files.length, passed: actual.length, elapsedMs: status.elapsedMs, exactRoster: true, inputHashesVerified: Object.keys(roster.inputHashes).length, preparationArtifactsExact: true, postCustodyReportedExact: true }, null, 2));
