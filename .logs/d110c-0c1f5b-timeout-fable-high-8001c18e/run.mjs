write('start.json',{command,cwd,start,pid:child.pid,requestedModel:'claude-fable-5-1[1m]',requestedEffort:'high',purpose:'one-off user-authorized timeout investigation'});
console.log(JSON.stringify({pid:child.pid,start}));
child.stdin.end(fs.readFileSync(path.join(out,'prompt.md')));
child.on('error',e=>write('spawn-error.json',{message:e.message}));
child.on('close',(status,signal)=>{fs.closeSync(stdout);fs.closeSync(stderr);write('status.json',{status,signal,start,finish:new Date().toISOString()});console.log(JSON.stringify({status,signal}));process.exitCode=status??1;});
